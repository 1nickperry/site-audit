import nodemailer from "nodemailer";
import { buildPdfReport, pdfReportFilename } from "./pdfReport.js";
import { categoryScore } from "../src/scores.js";

function getSmtpConfig() {
  const host = process.env.SMTP_HOST;
  const port = process.env.SMTP_PORT ? parseInt(process.env.SMTP_PORT, 10) : undefined;
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  const from = process.env.SMTP_FROM || user;
  
  if (!host || !port || !user || !pass) {
    return null;
  }
  
  return { host, port, user, pass, from };
}

export async function sendJobReport(job, recipientEmail) {
  const config = getSmtpConfig();
  
  if (!config) {
    const dryRun = process.env.EMAIL_DRY_RUN === "1";
    if (dryRun) {
      return handleDryRun(job, recipientEmail);
    }
    throw new Error("SMTP not configured. Set SMTP_HOST, SMTP_PORT, SMTP_USER, and SMTP_PASS environment variables.");
  }
  
  const transporter = nodemailer.createTransport({
    host: config.host,
    port: config.port,
    secure: config.port === 465,
    auth: {
      user: config.user,
      pass: config.pass
    }
  });
  
  const results = Array.isArray(job?.results) ? job.results : [];
  const siteUrl = job?.config?.url || "your site";
  const overall = categoryScore(results, null);
  const seo = categoryScore(results, "SEO");
  const speed = categoryScore(results, "speed");
  const security = categoryScore(results, "security");
  const failedCount = results.filter((r) => !r.pass).length;
  
  const pdfBuffer = await buildPdfReport(job);
  const filename = pdfReportFilename(job);
  
  const htmlBody = `
    <html>
      <head>
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; line-height: 1.6; color: #333; }
          .header { background: #f8f9fa; padding: 20px; border-radius: 8px; margin-bottom: 20px; }
          .scores { display: flex; gap: 15px; margin: 20px 0; }
          .score-box { flex: 1; padding: 15px; border-radius: 6px; text-align: center; }
          .score-box.good { background: #d4edda; color: #155724; }
          .score-box.warning { background: #fff3cd; color: #856404; }
          .score-box.bad { background: #f8d7da; color: #721c24; }
          .score-value { font-size: 32px; font-weight: bold; }
          .score-label { font-size: 14px; margin-top: 5px; }
          .summary { background: #fff; padding: 20px; border: 1px solid #dee2e6; border-radius: 8px; }
          .footer { margin-top: 30px; padding-top: 20px; border-top: 1px solid #dee2e6; color: #6c757d; font-size: 14px; }
        </style>
      </head>
      <body>
        <div class="header">
          <h1 style="margin: 0 0 10px 0;">Site Audit Results</h1>
          <p style="margin: 0; color: #6c757d;">Comprehensive SEO, speed, and security report for ${siteUrl}</p>
        </div>
        
        <div class="summary">
          <h2>Score Summary</h2>
          <div class="scores">
            <div class="score-box ${getScoreClass(overall)}">
              <div class="score-value">${overall ?? 0}%</div>
              <div class="score-label">Overall</div>
            </div>
            <div class="score-box ${getScoreClass(seo)}">
              <div class="score-value">${seo ?? 0}%</div>
              <div class="score-label">SEO</div>
            </div>
            <div class="score-box ${getScoreClass(speed)}">
              <div class="score-value">${speed ?? 0}%</div>
              <div class="score-label">Speed</div>
            </div>
            <div class="score-box ${getScoreClass(security)}">
              <div class="score-value">${security ?? 0}%</div>
              <div class="score-label">Security</div>
            </div>
          </div>
          
          <h3>Key Findings</h3>
          <ul>
            <li><strong>${job?.crawledPages ?? 0}</strong> pages crawled</li>
            <li><strong>${results.length}</strong> checks performed</li>
            <li><strong>${failedCount}</strong> checks found issues</li>
            <li><strong>${results.length - failedCount}</strong> checks passed</li>
          </ul>
          
          ${failedCount > 0 ? `
            <h3>Top Issues to Address</h3>
            <p>See the attached PDF report for detailed findings and actionable recommendations for each failing check.</p>
          ` : `
            <p style="color: #155724;"><strong>Great news!</strong> All checks passed. No issues found on your site.</p>
          `}
        </div>
        
        <div class="footer">
          <p>This report was generated by Site Audit on ${new Date().toLocaleString()}.</p>
          <p>Review the attached PDF for complete details, including affected URLs and step-by-step fix instructions.</p>
        </div>
      </body>
    </html>
  `;
  
  const mailOptions = {
    from: config.from,
    to: recipientEmail,
    subject: `Site Audit results for ${siteUrl}`,
    html: htmlBody,
    attachments: [
      {
        filename,
        content: pdfBuffer,
        contentType: "application/pdf"
      }
    ]
  };
  
  const info = await transporter.sendMail(mailOptions);
  return { success: true, messageId: info.messageId, filename };
}

async function handleDryRun(job, recipientEmail) {
  const { mkdirSync, writeFileSync } = await import("node:fs");
  const { join } = await import("node:path");
  const { fileURLToPath } = await import("node:url");
  
  const __dirname = join(fileURLToPath(import.meta.url), "..", "..");
  const outputDir = join(__dirname, "output");
  mkdirSync(outputDir, { recursive: true });
  
  const pdfBuffer = await buildPdfReport(job);
  const filename = pdfReportFilename(job);
  const filepath = join(outputDir, filename);
  
  writeFileSync(filepath, pdfBuffer);
  
  console.log(`[DRY RUN] Would send email to: ${recipientEmail}`);
  console.log(`[DRY RUN] PDF written to: ${filepath}`);
  
  return { success: true, dryRun: true, filename, filepath };
}

function getScoreClass(score) {
  if (score >= 80) return "good";
  if (score >= 50) return "warning";
  return "bad";
}
